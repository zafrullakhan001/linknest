import { SpeedTestResult, formatMbps, formatMs, historyToCsv, resultToShareText, speedTestTargetLabel } from './speedTestService';

function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export function exportSpeedTestHistoryJson(history: SpeedTestResult[]): void {
  const blob = new Blob([JSON.stringify(history, null, 2)], { type: 'application/json' });
  downloadBlob(blob, `linknest-speed-tests-${new Date().toISOString().slice(0, 10)}.json`);
}

export function exportSpeedTestHistoryCsv(history: SpeedTestResult[]): void {
  const blob = new Blob([historyToCsv(history)], { type: 'text/csv;charset=utf-8' });
  downloadBlob(blob, `linknest-speed-tests-${new Date().toISOString().slice(0, 10)}.csv`);
}

async function svgToPngDataUrl(svg: SVGSVGElement, width: number, height: number): Promise<string> {
  const clone = svg.cloneNode(true) as SVGSVGElement;
  clone.setAttribute('xmlns', 'http://www.w3.org/2000/svg');
  clone.setAttribute('width', String(width));
  clone.setAttribute('height', String(height));
  const xml = new XMLSerializer().serializeToString(clone);
  const svgUrl = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(xml)}`;
  const img = new Image();
  img.decoding = 'sync';
  await new Promise<void>((resolve, reject) => {
    img.onload = () => resolve();
    img.onerror = () => reject(new Error('Failed to render gauge SVG'));
    img.src = svgUrl;
  });
  const canvas = document.createElement('canvas');
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext('2d');
  if (!ctx) throw new Error('Canvas unavailable');
  ctx.fillStyle = '#ffffff';
  ctx.fillRect(0, 0, width, height);
  ctx.drawImage(img, 0, 0, width, height);
  return canvas.toDataURL('image/png');
}

export async function buildSpeedTestPngBlob(result: SpeedTestResult): Promise<Blob> {
  const gauge = document.querySelector('[data-speed-gauge]') as SVGSVGElement | null;
  const width = 920;
  const height = 560;
  const canvas = document.createElement('canvas');
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext('2d');
  if (!ctx) throw new Error('Canvas unavailable');

  // Background
  const grad = ctx.createLinearGradient(0, 0, width, height);
  grad.addColorStop(0, '#f8fafc');
  grad.addColorStop(1, '#e0f2fe');
  ctx.fillStyle = grad;
  ctx.fillRect(0, 0, width, height);

  // Card
  ctx.fillStyle = '#ffffff';
  roundRect(ctx, 28, 28, width - 56, height - 56, 28);
  ctx.fill();
  ctx.strokeStyle = '#e2e8f0';
  ctx.lineWidth = 2;
  ctx.stroke();

  ctx.fillStyle = '#0f172a';
  ctx.font = 'bold 28px system-ui,Segoe UI,sans-serif';
  ctx.fillText('LinkNest Speed Test', 56, 78);
  ctx.font = '14px system-ui,Segoe UI,sans-serif';
  ctx.fillStyle = '#64748b';
  ctx.fillText(new Date(result.at).toLocaleString(), 56, 102);
  ctx.fillText(
    `${speedTestTargetLabel(result.target, result.meta.endpointHost)}${
      result.target === 'custom' ? (result.meta.endpointMode === 'proxy' ? ' via LinkNest host' : ' browser-direct') : ''
    } · ${result.connectionMode} · ${result.profile}`,
    56,
    124
  );

  if (gauge) {
    try {
      const png = await svgToPngDataUrl(gauge, 280, 240);
      const img = new Image();
      await new Promise<void>((resolve, reject) => {
        img.onload = () => resolve();
        img.onerror = () => reject(new Error('gauge image'));
        img.src = png;
      });
      ctx.drawImage(img, 56, 150, 280, 240);
    } catch {
      /* ignore gauge render failure */
    }
  }

  const metrics: Array<[string, string]> = [
    ['Download', formatMbps(result.downloadMbps)],
    ['Upload', formatMbps(result.uploadMbps)],
    ['Ping', formatMs(result.pingMs)],
    ['Jitter', formatMs(result.jitterMs)],
    ['Loaded ping', formatMs(result.loadedPingMs)],
    ['Bufferbloat', `+${formatMs(result.bufferbloatDownloadMs)}`],
    ['Quality', `${result.quality.label} (${result.score}/100)`],
    ['IP', result.meta.ip || '—'],
  ];

  let y = 170;
  ctx.font = 'bold 13px system-ui,Segoe UI,sans-serif';
  for (const [label, value] of metrics) {
    ctx.fillStyle = '#64748b';
    ctx.fillText(label.toUpperCase(), 380, y);
    ctx.fillStyle = '#0f172a';
    ctx.font = 'bold 22px system-ui,Segoe UI,sans-serif';
    ctx.fillText(value, 380, y + 28);
    ctx.font = 'bold 13px system-ui,Segoe UI,sans-serif';
    y += 48;
  }

  if (result.useCaseGrades?.length) {
    ctx.fillStyle = '#64748b';
    ctx.font = 'bold 12px system-ui,Segoe UI,sans-serif';
    ctx.fillText(
      'Use cases: ' + result.useCaseGrades.map((g) => `${g.label} ${g.grade}`).join(' · '),
      56,
      height - 70
    );
  }

  ctx.fillStyle = '#94a3b8';
  ctx.font = '12px system-ui,Segoe UI,sans-serif';
  ctx.fillText('Generated by LinkNest Monitoring', 56, height - 48);

  return await new Promise((resolve, reject) => {
    canvas.toBlob((blob) => {
      if (!blob) reject(new Error('PNG encode failed'));
      else resolve(blob);
    }, 'image/png');
  });
}

function roundRect(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  w: number,
  h: number,
  r: number
): void {
  const radius = Math.min(r, w / 2, h / 2);
  ctx.beginPath();
  ctx.moveTo(x + radius, y);
  ctx.arcTo(x + w, y, x + w, y + h, radius);
  ctx.arcTo(x + w, y + h, x, y + h, radius);
  ctx.arcTo(x, y + h, x, y, radius);
  ctx.arcTo(x, y, x + w, y, radius);
  ctx.closePath();
}

export async function downloadSpeedTestPng(result: SpeedTestResult): Promise<void> {
  const blob = await buildSpeedTestPngBlob(result);
  downloadBlob(blob, `linknest-speed-${new Date(result.at).toISOString().slice(0, 19).replace(/[:T]/g, '-')}.png`);
}

export async function copySpeedTestText(result: SpeedTestResult): Promise<void> {
  await navigator.clipboard.writeText(resultToShareText(result));
}

export async function copySpeedTestPng(result: SpeedTestResult): Promise<boolean> {
  try {
    const blob = await buildSpeedTestPngBlob(result);
    if (!navigator.clipboard || !('ClipboardItem' in window)) return false;
    await navigator.clipboard.write([new ClipboardItem({ 'image/png': blob })]);
    return true;
  } catch {
    return false;
  }
}
